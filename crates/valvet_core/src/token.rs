use crate::source::Span;

#[derive(Debug, Clone, PartialEq)]
pub enum Tok {
    // Keywords (Stage A usable)
    Fun,
    Val,
    Var,
    If,
    Else,
    While,
    Return,
    True,
    False,
    For,
    Loop,
    Break,
    Continue,
    // Reserved but deferred (parsed as keyword, rejected in parser)
    Match,
    Defer,
    Unsafe,
    Extern,
    Struct,
    Enum,
    Trait,
    Impl,
    Type,
    Const,
    Static,
    Dyn,
    Move,
    Mut,
    Ref,
    Pub,
    Self_,
    SelfTy,
    As,
    In,
    Use,
    Where,
    When,
    Let,
    // Literals / names
    Ident(String),
    IntLit(i64),
    FloatLit(f64),
    StrLit(String),
    CharLit(char),
    /// Explicit lifetime `'a` (disambiguated from char literals in the lexer).
    Lifetime(String),
    // Symbols
    Plus,
    Minus,
    Star,
    Slash,
    Percent,
    EqEq,
    BangEq,
    Lt,
    LtEq,
    Gt,
    GtEq,
    AndAnd,
    OrOr,
    BitOr,
    Bang,
    Eq,
    PlusEq,
    MinusEq,
    StarEq,
    SlashEq,
    PercentEq,
    LParen,
    RParen,
    LBrace,
    RBrace,
    LBracket,
    RBracket,
    Comma,
    Colon,
    ColonColon,
    Semi,
    Dot,
    DotDot,
    DotDotEq,
    Arrow,
    Question,
    DotQuestion,
    Amp,
    AmpMut,
    /// `@` introducing a units-of-measure annotation (J: `@m/s`).
    At,
    /// `^` power in unit expressions (`m/s^2`).
    Caret,
    // Layout
    Nl,
    Eof,
}

#[derive(Debug, Clone)]
pub struct Token {
    pub kind: Tok,
    pub span: Span,
}

pub fn keyword(word: &str) -> Option<Tok> {
    Some(match word {
        "fun" => Tok::Fun,
        "val" => Tok::Val,
        "var" => Tok::Var,
        "if" => Tok::If,
        "else" => Tok::Else,
        "while" => Tok::While,
        "return" => Tok::Return,
        "true" => Tok::True,
        "false" => Tok::False,
        "for" => Tok::For,
        "loop" => Tok::Loop,
        "break" => Tok::Break,
        "continue" => Tok::Continue,
        "match" => Tok::Match,
        "defer" => Tok::Defer,
        "unsafe" => Tok::Unsafe,
        "extern" => Tok::Extern,
        "struct" => Tok::Struct,
        "enum" => Tok::Enum,
        "trait" => Tok::Trait,
        "impl" => Tok::Impl,
        "type" => Tok::Type,
        "const" => Tok::Const,
        "static" => Tok::Static,
        "dyn" => Tok::Dyn,
        "move" => Tok::Move,
        "mut" => Tok::Mut,
        "ref" => Tok::Ref,
        "pub" => Tok::Pub,
        "self" => Tok::Self_,
        "Self" => Tok::SelfTy,
        "as" => Tok::As,
        "in" => Tok::In,
        "use" => Tok::Use,
        "where" => Tok::Where,
        "when" => Tok::When,
        "let" => Tok::Let,
        _ => return None,
    })
}
